"""Schemas for the customer-support assistant."""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field


class AssistantQuestion(BaseModel):
    question: str = Field(min_length=2, max_length=1000)
    conversation_id: str | None = Field(default=None, max_length=64)


class AssistantSource(BaseModel):
    """A knowledge-base entry that supports the answer."""

    id: int
    question: str
    category: str


class AssistantAnswer(BaseModel):
    """The assistant's reply.

    ``mode`` makes the provenance explicit:

    * ``knowledge_base`` - answered directly from approved ARCH information.
    * ``llm_grounded``   - generated by the configured provider, grounded on the
      approved information above.
    * ``not_covered``    - the question is outside the approved information.
    """

    answer: str
    mode: str
    sources: list[AssistantSource] = []
    provider: str | None = None
    model: str | None = None
    created_at: datetime
    conversation_id: str | None = None
    disclaimer: str = "Answers are based on approved ARCH information only."
